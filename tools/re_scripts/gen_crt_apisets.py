#!/usr/bin/env python3
"""gen_crt_apisets.py - build new_stubs/apisets_crt.txt from the Windows 10 api-ms-win-crt-*.dll files.

Why our own CRT api-set DLLs instead of Microsoft's: Windows 10's api-ms-win-crt-*.dll are pure
forwarders to ucrtbase.dll and import nothing. KernelEx resolves a forwarder only if the target is
ALREADY loaded (core/resolver.cpp: GetModuleHandle, no LoadLibrary), so a program that imports
api-ms-win-crt-runtime-l1-1-0.dll but not ucrtbase.dll would get NULL function pointers. Our shells
carry the same forwarders plus a static "#dep" import of ucrtbase.dll, which makes the 9x loader map
ucrtbase first (same trick as the api-ms-win-core-* shells).

  python3 gen_crt_apisets.py <dir with api-ms-win-crt-*.dll> -o ../../new_stubs/apisets_crt.txt
No third-party modules.
"""
import argparse, os, struct, sys


def pe_exports(path):
    d = open(path, 'rb').read()
    pe = struct.unpack_from('<I', d, 0x3c)[0]
    nsec = struct.unpack_from('<H', d, pe + 6)[0]
    optsz = struct.unpack_from('<H', d, pe + 20)[0]
    opt = pe + 24
    exp_rva, exp_size = struct.unpack_from('<II', d, opt + 96)
    secs = [struct.unpack_from('<8sIIII', d, opt + optsz + 40 * i) for i in range(nsec)]

    def off(rva):
        for _, vs, va, rs, ro in secs:
            if va <= rva < va + max(vs, rs):
                return ro + rva - va
        raise ValueError(hex(rva))

    def cstr(rva):
        o = off(rva)
        return d[o:d.index(b'\0', o)].decode('ascii')

    if not exp_rva:
        return []
    _, _, _, _, _, base, nf, nn, af, an, ao = struct.unpack_from('<IIHHIIIIIII', d, off(exp_rva))
    res = []
    for i in range(nn):
        name = cstr(struct.unpack_from('<I', d, off(an) + 4 * i)[0])
        idx = struct.unpack_from('<H', d, off(ao) + 2 * i)[0]
        rva = struct.unpack_from('<I', d, off(af) + 4 * idx)[0]
        fwd = cstr(rva) if exp_rva <= rva < exp_rva + exp_size else None
        res.append((name, fwd))
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('win10dir')
    ap.add_argument('-o', required=True)
    ap.add_argument('--anchor', default='_errno', help='ucrtbase function imported statically by every shell')
    a = ap.parse_args()
    files = sorted(f for f in os.listdir(a.win10dir) if f.lower().startswith('api-ms-win-crt-') and f.lower().endswith('.dll'))
    if not files:
        sys.exit('no api-ms-win-crt-*.dll in ' + a.win10dir)
    lines, total = [], 0
    for f in files:
        s = f[:-4].lower()
        n = 0
        for name, fwd in pe_exports(os.path.join(a.win10dir, f)):
            if not fwd:
                sys.exit('%s!%s is not a forwarder' % (f, name))
            tdll, tfn = fwd.split('.', 1)
            if tdll.lower() != 'ucrtbase' or tfn != name:
                sys.exit('%s!%s forwards to %s (expected ucrtbase.%s)' % (f, name, fwd, name))
            lines.append('%s %s ucrtbase' % (s, name))
            n += 1
        lines.insert(0, '#dep %s ucrtbase %s' % (s, a.anchor))
        total += n
    with open(a.o, 'w') as o:
        o.write('# GENERATED by tools/re_scripts/gen_crt_apisets.py from the Windows 10 api-ms-win-crt-*.dll.\n')
        o.write('# <apiset> <function> ucrtbase  - forwarders to the genuine Windows 10 ucrtbase.dll\n')
        o.write('\n'.join(sorted(l for l in lines if l.startswith('#dep'))) + '\n')
        o.write('\n'.join(l for l in lines if not l.startswith('#')) + '\n')
    print('%d sets, %d forwarders -> %s' % (len(files), total, a.o))


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Generate build/kexnt_apitable.c: the KernelEx api-library table for kexnt.dll.

KernelEx loads every library named in core.ini "contents=" and calls its get_api_table().
Each table lists, per system DLL (KERNEL32.DLL, NTDLL.DLL), name -> address pairs; the
resolver then hands those addresses to any KernelEx-enabled module that imports the name
(static import or GetProcAddress). Names must be sorted by strcmp (kexcoresdk.h).

usage: gen_apitable.py build/kexnt.def kexnt_targets.txt > build/kexnt_apitable.c
"""
import sys


def ident_of(dll):
    return ''.join(c if c.isalnum() else '_' for c in dll.lower())


# Build 131: NTDLL functions that Chromium's sandbox (Firefox 115 content processes) patches in a child it starts:
# before patching it checks that the function begins like an NT system-call stub (service_resolver_32.cc
# ServiceResolverThunk::IsFunctionAService: mov eax,id / mov edx,X / call edx / ret N). Their gates take exactly
# that shape - mov eax,<gate> / mov edx,_kexsvc_dispatch / call edx / ret <bytes> / nop - and behave like a plain gate.
SVC_SHAPED = {'NtMapViewOfSection', 'NtUnmapViewOfSection', 'NtSetInformationThread', 'NtOpenThreadToken',
              'NtOpenThreadTokenEx', 'NtOpenThread', 'NtOpenProcess', 'NtOpenProcessToken', 'NtOpenProcessTokenEx',
              'NtCreateFile', 'NtOpenFile', 'NtQueryAttributesFile', 'NtQueryFullAttributesFile',
              'NtSetInformationFile', 'NtCreateKey', 'NtOpenKey', 'NtOpenKeyEx', 'NtCreateEvent', 'NtOpenEvent',
              'NtCreateSection'}

def main(def_path, targets_path, cdecl_path=None):
    exports = {}                                    # export name -> stdcall symbol (kex_X@N)
    for line in open(def_path):
        line = line.strip()
        if '=' in line and not line.startswith(';'):
            name, sym = (s.strip() for s in line.split('=', 1))
            exports[name] = sym
    if cdecl_path:                                  # cdecl functions (MSVCRT): "<name> <symbol>"
        for line in open(cdecl_path):
            p = line.split()
            if len(p) == 2 and not line.startswith('#'):
                exports[p[0]] = p[1]

    ords = {}                                 # DLL -> [(ordinal, export name)]
    tables = {'KERNEL32': [], 'NTDLL': []}   # more DLLs are added as kexnt_targets.txt names them
    for line in open(targets_path):
        line = line.split(' #', 1)[0].split() if not line.startswith('#') else []
        if len(line) != 2:
            continue
        name, dlls = line
        if name not in exports:
            sys.exit(f"gen_apitable: {name} listed in {targets_path} but not exported by kexnt.dll")
        for dll in dlls.split(','):
            if '@' in dll:                          # DLL@ordinal: route an import by ordinal (WSOCK32@52)
                dll, ordv = dll.split('@', 1)
                ords.setdefault(dll.upper(), []).append((int(ordv), name))
                tables.setdefault(dll.upper(), [])
            else:
                tables.setdefault(dll.upper(), []).append(name)

    routed = {n for v in tables.values() for n in v} | {n for v in ords.values() for _, n in v}
    for name in sorted(set(exports) - routed):
        print(f"gen_apitable: note: {name} not routed through any system DLL", file=sys.stderr)

    syms = sorted({exports[n] for n in routed})
    ident = {s: f"k_{i}" for i, s in enumerate(syms)}
    # Build 89: every published (DLL, name) goes through a gate thunk (gate_ext.c). In a program built for
    # Windows 9x (subsystem 4.x, no explicit NT profile) the thunk forwards to what KernelEx would give without
    # kexnt (kexbasen / kexbases / the system DLL); otherwise it jumps straight to kexnt's function.
    gates = []                                       # (dll file name, export name, symbol)
    gate_of = {}
    for dll, names in tables.items():
        file = dll if '.' in dll else dll + '.DLL'
        for n in names:
            if (file, n) not in gate_of:
                gate_of[(file, n)] = len(gates); gates.append((file, n, exports[n]))
    for dll, lst in ords.items():
        file = dll if '.' in dll else dll + '.DLL'
        for o, n in lst:
            if (file, n) not in gate_of:
                gate_of[(file, n)] = len(gates); gates.append((file, n, exports[n]))
    out = ["/* Generated by gen_apitable.py - do not edit. */",
           "/* Layout must match common/kexcoresdk.h (apilib_named_api / apilib_api_table). */",
           "typedef struct { const char *name; unsigned long addr; } apilib_named_api;",
           "typedef struct { unsigned short ord; unsigned long addr; } apilib_unnamed_api;",
           "typedef struct { const char *target_library; const apilib_named_api *named_apis; int named_apis_count;",
           "                 const apilib_unnamed_api *ordinal_apis; int ordinal_apis_count; } apilib_api_table;",
           ""]
    out += [f'extern void {ident[s]}(void) __asm__("_{s}");' for s in syms]
    out.append("\n/* gate thunks: modern process -> kexnt's function; Windows 9x program -> kexgate_slow (gate_ext.c) */")
    out.append('__asm__(".text\\n"')
    for i, (f, n, sym) in enumerate(gates):
        if f.upper() == 'NTDLL.DLL' and n in SVC_SHAPED:
            nb = int(sym.rsplit('@', 1)[1])          # stdcall argument bytes
            out.append(f'    "_kg_{i}:\\n  .byte 0xB8\\n  .long {i}\\n  .byte 0xBA\\n  .long _kexsvc_dispatch\\n'
                       f'  .byte 0xFF, 0xD2, 0xC2\\n  .word {nb}\\n  .byte 0x90\\n"')
        else:
            out.append(f'    "_kg_{i}:\\n  cmpl $2, _kex_gate_state\\n  je \\"_{sym}\\"\\n  pushl ${i}\\n  jmp _kexgate_slow\\n"')
    # build 131: the service-shaped gates' common tail (see SVC_SHAPED): drop the return address "call edx" pushed,
    # then exactly what a plain gate does - modern process: kexgate_tab[eax].real; Windows 9x program: kexgate_slow
    out.append('    "_kexsvc_dispatch:\\n  popl %ecx\\n  cmpl $2, _kex_gate_state\\n  jne 1f\\n'
               '  leal (%eax,%eax,2), %ecx\\n  jmp *_kexgate_tab+8(,%ecx,4)\\n1:\\n  pushl %eax\\n  jmp _kexgate_slow\\n"')
    out.append(');')
    out += [f'extern void kg_{i}(void) __asm__("_kg_{i}");' for i in range(len(gates))]
    out.append("typedef struct { const char *dll, *name; void (*real)(void); } kexgate_entry;")
    out.append(f"const int kexgate_count = {len(gates)};")
    out.append("const kexgate_entry kexgate_tab[] = {")
    out += [f'    {{ "{f}", "{n}", {ident[sym]} }},' for f, n, sym in gates]
    out.append("};")
    for dll, names in tables.items():
        out.append(f"\nstatic const apilib_named_api {ident_of(dll)}_apis[] = {{")
        file = dll if '.' in dll else dll + '.DLL'
        out += [f'    {{ "{n}", (unsigned long)kg_{gate_of[(file, n)]} }},' for n in sorted(names)]
        out.append("};")
        if dll in ords:
            out.append(f"static const apilib_unnamed_api {ident_of(dll)}_ords[] = {{")
            file = dll if '.' in dll else dll + '.DLL'
            out += [f'    {{ {o}, (unsigned long)kg_{gate_of[(file, n)]} }},' for o, n in sorted(ords[dll])]
            out.append("};")
    out.append("\nstatic const apilib_api_table api_tables[] = {")
    for dll, names in tables.items():
        file = dll if '.' in dll else dll + '.DLL'
        o = f"{ident_of(dll)}_ords, {len(ords[dll])}" if dll in ords else "0, 0"
        out.append(f'    {{ "{file}", {ident_of(dll)}_apis, {len(names)}, {o} }},')
    out.append("    { 0, 0, 0, 0, 0 }\n};")
    out.append("\n/* Exported undecorated (cdecl, listed in kexnt.def), as KernelEx's fgat_t expects. */")
    out.append("const apilib_api_table *get_api_table(void) { return api_tables; }")
    print("\n".join(out))
    print("gen_apitable: " + ", ".join(f"{d} {len(n)}" for d, n in tables.items()) + " names", file=sys.stderr)


if __name__ == '__main__':
    main(*sys.argv[1:4])

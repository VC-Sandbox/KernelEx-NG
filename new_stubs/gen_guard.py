#!/usr/bin/env python3
"""Generate guard_gen.c: guarded pass-throughs (gdiguard_ext.c guard_call) for every export of a Windows 98
system DLL listed in the data files ("Name argbytes", argbytes from MinGW's import-library @N decoration).
usage: gen_guard.py GDI32=data/gdi32_guard.txt USER32=data/user32_guard.txt ... > guard_gen.c
       (prints the kexnt_targets.txt lines to stderr)
Each export kex_<Name>@N is a 2-instruction stub: push <index>; jmp kexg_common. kexg_common calls
kexg_dispatch(index, args) (C, in gdiguard_ext.c) and returns with "ret N" semantics for that index.
The same name in two DLLs is not supported (none of the Windows 98 lists overlap)."""
import sys
dlls, ents, seen = [], [], set()
for spec in sys.argv[1:]:
    dll, path = spec.split('=', 1)
    di = len(dlls); dlls.append(dll.upper() + '.DLL')
    for l in open(path):
        if not l.strip() or l.startswith('#'): continue
        n, a = l.split()[:2]
        if n in seen: sys.exit(f'gen_guard: {n} listed twice')
        seen.add(n); ents.append((n, int(a), di))
o = ['/* Generated by gen_guard.py - do not edit. Guarded system-DLL pass-throughs, see gdiguard_ext.c. */',
     '#include "kexnt_common.h"', '']
o.append('const char *const kexg_dlls[] = {' + ', '.join(f'"{d}"' for d in dlls) + '};')
o.append('const char *const kexg_names[] = {')
o += [f'    "{n}",' for n, a, d in ents]
o.append('};')
o.append('const unsigned short kexg_nargs[] = {')
o += [f'    {a // 4},' for n, a, d in ents]
o.append('};')
o.append('const unsigned char kexg_dll[] = {')
o += ['    ' + ', '.join(str(d) for n, a, d in ents[i:i + 32]) + ',' for i in range(0, len(ents), 32)]
o.append('};')
o.append(f'const int kexg_count = {len(ents)};')
o.append('FARPROC kexg_cache[%d];' % len(ents))
o.append('__asm__(".text\\n"')
for i, (n, a, d) in enumerate(ents):
    o.append(f'    ".globl \\"_kex_{n}@{a}\\"\\n\\"_kex_{n}@{a}\\":\\n  pushl ${i}\\n  jmp _kexg_common\\n"')
o.append(');')
# build 55: address of every stub, so kexnt can point another module's import table at them (OPENGL32.DLL)
o.append('__asm__(".section .rdata\\n.globl _kexg_stubs\\n.p2align 2\\n_kexg_stubs:\\n"')
for i, (n, a, d) in enumerate(ents):
    o.append(f'    "  .long \\"_kex_{n}@{a}\\"\\n"')
o.append('    ".text\\n");')
print('\n'.join(o))
for n, a, d in ents:
    print(f'{n} {dlls[d][:-4]}', file=sys.stderr)

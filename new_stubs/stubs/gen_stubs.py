#!/usr/bin/env python3
"""gen_stubs.py <stubs.txt> <mingw_decor.txt> <outdir>
Writes <outdir>/<base>.gen.c and <base>.def for every DLL in stubs.txt, plus <outdir>/stub_dlls.txt
(one "<file name> <base>" per DLL). Stack sizes come from decorated MinGW import-library names, so every
stub pops exactly what its callers push."""
import sys, os, collections

spec_path, decor_path, out = sys.argv[1:4]
decor = collections.defaultdict(set)
for l in open(decor_path):
    n, b = l.strip().rsplit('@', 1)
    decor[n].add(int(b))

dlls = collections.OrderedDict()
for ln, l in enumerate(open(spec_path), 1):
    l = l.split('#', 1)[0].split()
    if not l:
        continue
    if len(l) != 3:
        sys.exit(f"{spec_path}:{ln}: expected <dll> <function> <behaviour>")
    dlls.setdefault(l[0], []).append((l[1], l[2]))

def base_of(dll):
    return os.path.splitext(dll)[0].lower()

os.makedirs(out, exist_ok=True)
listing = []
for dll, funcs in dlls.items():
    b = base_of(dll)
    listing.append(f"{dll} {b}")
    c = ["/* generated by gen_stubs.py from stubs.txt - do not edit */",
         "#include <windows.h>", ""]
    d = [f"LIBRARY {dll}", "EXPORTS"]
    for name, beh in funcs:
        ordn = ''
        if '%' in name:                          # build 128: export by this ordinal too (MMDevAPI #17)
            name, o = name.split('%'); ordn = f' @{int(o)}'
        if '@' in name:                          # size given in stubs.txt (DLL not in the MinGW libraries)
            name, given = name.split('@'); sizes = {int(given)}
        else:
            sizes = decor.get(name)
        if not sizes or len(sizes) != 1:
            sys.exit(f"gen_stubs: no unique stdcall size for {name} ({sizes})")
        nb = next(iter(sizes)); na = nb // 4
        if beh == 'custom':                      # hand-written in stubs/<base>.c under the real name
            d.append(f"    {name}={name}@{nb}{ordn}")
            continue
        d.append(f"    {name}=stub_{name}@{nb}{ordn}")   # private name: no clash with SDK prototypes
        parts = beh.split(':')
        kind = parts[0]
        outs = [int(x) for x in parts[2].split(',')] if len(parts) > 2 and parts[2] else []
        args = ", ".join(f"ULONG_PTR a{i}" for i in range(1, na + 1)) or "void"
        rtype = {'hr': 'LONG', 'bool': 'BOOL', 'ptr': 'void *', 'val': 'ULONG_PTR', 'u64': 'ULONGLONG', 'void': 'void'}[kind]
        body = []
        for o in outs:
            if o > na:
                sys.exit(f"gen_stubs: {name}: out argument {o} > {na} arguments")
            body.append(f"    if (a{o}) *(ULONG_PTR *)a{o} = 0;")
        if kind == 'hr':
            body.append(f"    return (LONG)0x{parts[1]}UL;")
        elif kind == 'bool':
            body.append(f"    SetLastError({parts[1]}); return FALSE;")
        elif kind == 'ptr':
            body.append(f"    SetLastError({parts[1]}); return NULL;")
        elif kind == 'val':
            body.append(f"    return (ULONG_PTR)({parts[1]});")
        elif kind == 'u64':
            body.append(f"    return {parts[1]}ULL;")
        c.append(f"{rtype} WINAPI stub_{name}({args});")
        c.append(f"{rtype} WINAPI stub_{name}({args})")
        c.append("{")
        c += body or ["    return;"]
        c.append("}")
        c.append("")
    open(os.path.join(out, b + ".gen.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(out, b + ".def"), "w").write("\n".join(d) + "\n")
open(os.path.join(out, "stub_dlls.txt"), "w").write("\n".join(listing) + "\n")
print(f"gen_stubs: {len(dlls)} DLLs, {sum(len(v) for v in dlls.values())} functions")

#!/usr/bin/env python3
"""gen_apiset_thunks.py <apiset> <builddir> <is_clang> <table>...

Writes <builddir>/<apiset>.def, <apiset>.fwd (clang forwarders) and <apiset>.thunks.c.

Why thunks: a PE forwarder ("Name=kernel32.Name") is resolved by KernelEx core
(core/resolver.cpp OriExportFromName -> GetProcAddress). Core lives in the shared arena and
get_config() gives shared modules NO api configuration, so the lookup returns the *native*
Win98 export: NULL for functions only KernelEx provides (e.g. HeapQueryInformation ->
"linked to missing export"), and the native stub for *W functions KernelEx replaces.
Therefore every entry whose target is a system DLL becomes a lazy jump thunk: the first call
runs GetProcAddress from THIS (private-arena) module, which KernelEx routes through the
process's api configuration, then patches the jump. Entries whose target is one of our own
real DLLs (kexnt, ucrtbase) stay plain forwarders - those resolve correctly (kexroute test).
"""
import sys

FORWARD_OK = {'kexnt', 'ucrtbase'}

apiset, bdir, is_clang = sys.argv[1], sys.argv[2], sys.argv[3] == '1'
entries = []
for t in sys.argv[4:]:
    for line in open(t):
        p = line.split()
        if len(p) == 3 and not line.startswith('#') and p[0] == apiset:
            entries.append((p[1], p[2]))

fwd = [(n, d) for n, d in entries if d.lower() in FORWARD_OK]
thk = [(n, d) for n, d in entries if d.lower() not in FORWARD_OK]

with open('%s/%s.def' % (bdir, apiset), 'w') as o:
    o.write('LIBRARY %s.dll\nEXPORTS\n    KexApiSetInfo@0\n' % apiset)
    if not is_clang:
        for n, d in fwd:
            o.write('    %s=%s.%s\n' % (n, d, n))
    for n, d in thk:
        o.write('    %s=kt_%s\n' % (n, n))
with open('%s/%s.fwd' % (bdir, apiset), 'w') as o:
    for n, d in fwd:
        o.write('-Wl,-Xlink=-export:%s=%s.%s\n' % (n, d, n))

c = ['/* generated by gen_apiset_thunks.py - lazy thunks for %s */' % apiset,
     '#include "kexnt_common.h"']
if thk:
    c.append('const char *const kt_names[] = {%s};' % ', '.join('"%s"' % n for n, _ in thk))
    c.append('const char *const kt_dlls[] = {%s};' % ', '.join('"%s.dll"' % d for _, d in thk))
    c.append(''.join('extern void kt_lazy_%d(void);\n' % i for i in range(len(thk))))
    c.append('void *kt_ptr[%d] = {%s};' % (len(thk), ', '.join('kt_lazy_%d' % i for i in range(len(thk)))))
    c.append('''
/* Resolve thunk i through KernelEx (caller = this module), patch the jump, return the target. */
void *__cdecl kt_resolve(int i)
{
    DWORD le = GetLastError();
    HMODULE h = GetModuleHandleA(kt_dlls[i]);
    void *p;
    if (!h) h = LoadLibraryA(kt_dlls[i]);
    p = h ? (void *)GetProcAddress(h, kt_names[i]) : NULL;
    if (!p) {
        char msg[300];               /* kernel32-only formatting: shells must not import user32 */
        lstrcpyA(msg, APISET_NAME ": ");
        lstrcatA(msg, kt_dlls[i]); lstrcatA(msg, "!"); lstrcatA(msg, kt_names[i]);
        lstrcatA(msg, " is not available on this system (KernelEx-NG)");
        FatalAppExitA(0, msg);
    }
    InterlockedExchange((LONG *)&kt_ptr[i], (LONG)(ULONG_PTR)p);
    SetLastError(le);
    return p;
}
''')
    asm = ['__asm__(".text\\n"',
           '"_kt_common:\\n\\t"',
           '"pushl %ecx\\n\\tpushl %edx\\n\\t"',
           '"pushl 8(%esp)\\n\\t"',            # index pushed by the lazy stub
           '"call _kt_resolve\\n\\t"',
           '"addl $4, %esp\\n\\tpopl %edx\\n\\tpopl %ecx\\n\\t"',
           '"addl $4, %esp\\n\\t"',            # drop the index
           '"jmp *%eax\\n"']
    for i, (n, _) in enumerate(thk):
        asm.append('".globl _kt_%s\\n_kt_%s: jmp *_kt_ptr+%d\\n"' % (n, n, 4 * i))
        asm.append('".globl _kt_lazy_%d\\n_kt_lazy_%d: pushl $%d\\n\\tjmp _kt_common\\n"' % (i, i, i))
    asm.append(');')
    c += asm
else:
    c.append('int kt_none;')
open('%s/%s.thunks.c' % (bdir, apiset), 'w').write('\n'.join(c) + '\n')

/* spiall.c - probe: which SystemParametersInfo GET actions Windows 98 answers (WPF's SystemParameters reads many and
 * throws when one returns FALSE). Tries every action in the SPI ranges with a zeroed buffer. SPIALL.EXE > out.txt */
#include <windows.h>
#include <stdio.h>
static void t(UINT a)
{
    BYTE buf[2048]; BOOL rA, rW; DWORD eA, eW;
    memset(buf, 0, sizeof(buf)); *(UINT *)buf = 500; SetLastError(0); rA = SystemParametersInfoA(a, sizeof(buf), buf, 0); eA = GetLastError();
    memset(buf, 0, sizeof(buf)); *(UINT *)buf = 500; SetLastError(0); rW = SystemParametersInfoW(a, sizeof(buf), buf, 0); eW = GetLastError();
    if (!rA || !rW) printf("0x%04x A %d err %lu  W %d err %lu\n", a, rA, eA, rW, eW);
}
int main(void)
{
    UINT a; static const UINT get[] = { 0x01,0x03,0x05,0x0a,0x0e,0x10,0x12,0x16,0x18,0x19,0x1b,0x1f,0x24,0x26,0x29,0x2c,0x30,0x32,
        0x34,0x36,0x38,0x3a,0x3c,0x3e,0x40,0x42,0x44,0x46,0x48,0x4a,0x4c,0x4e,0x50,0x52,0x55,0x59,0x5a,0x5c,0x5e,0x62,0x64,0x66,
        0x68,0x6a,0x6c,0x6e,0x70,0x72,0x74,0x76,0x80,0x82,0x84,0x86,0x88,0x8a,0x8c,0x8e,0x90,0x92,0x94,0x96,0x98,0x9a,0x9c };
    for (a = 0; a < sizeof(get) / sizeof(get[0]); a++) t(get[a]);
    for (a = 0x1000; a <= 0x1026; a += 2) t(a);
    for (a = 0x2000; a <= 0x2016; a += 2) t(a);
    printf("done\n");
    return 0;
}
